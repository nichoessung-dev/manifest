"""One finds count for the whole site (owner, 15 Nov 2026: "this bugs when you refresh, also make everywhere on the site
update when the amount of finds update").

The page used to show the server's number (all finds, hidden ones included, rounded to the thousand: "12,000+") and
then the app replaced it with its own (visible finds, to the hundred: "8,100+"), so the search box flipped on every load.
Now this script is the one source: visible finds = the catalogue minus data/reported.json "hidden" (reports, bad photos,
duplicates), minus dead listings (data/link_health.json) and minus partner-swap look-alikes (data/link_swaps.json),
rounded down to the hundred. It writes:
  - functions/_lib/counts.js  FINDS_PLUS / QC_PLUS / FINDS_N for the server pages and the homepage rewrite (site.js)
  - the same number into the fixed copy of the static files (index.html outside the catalogue block, privacy, terms,
    how-to-order, links, llms.txt, the web app manifest, the chat assistant's prompt)
The app no longer rewrites the number in the browser. Runs in the Reports workflow (every 2 h) after bake_reports.py.

  python scripts/bake_counts.py [--check]
"""
import json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalog_common import ROOT, load_catalog  # noqa: E402

FILES = ["index.html", "privacy.html", "terms.html", "how-to-order.html", "links.html", "llms.txt", "manifest.webmanifest",
         "functions/api/chat.js"]
NUM = re.compile(r"(?<![$¥€£\d.,])(?:[5-9]|1\d),\d{3}\+")          # same rule as site.js LIVE_RULES
ABOUT = re.compile(r"(about )(?:[5-9]|1\d),\d{3}( replica fashion finds)")


def load(p, d):
    try:
        with open(os.path.join(ROOT, p), encoding="utf-8") as f: return json.load(f)
    except Exception: return d


def counts():
    _, items, _, _ = load_catalog()
    gone = set(map(str, (load("data/reported.json", {}) or {}).get("hidden") or []))
    gone |= set(map(str, (load("data/link_health.json", {}) or {}).get("dead") or []))
    gone |= set(map(str, (load("data/link_swaps.json", {}) or {}).get("hide") or []))
    vis = [p for p in items if str(p.get("id")) not in gone]
    qc = sum(1 for p in vis if (p.get("qc") or 0) >= 1)
    plus = lambda n: f"{n // 100 * 100:,}+"
    return len(vis), plus(len(vis)), (plus(qc) if qc >= 100 else str(qc)), qc


def main():
    n, finds, qcl, qc = counts()
    js = (f"// Generated by scripts/bake_counts.py (Reports workflow). Do not edit by hand.\n"
          f"export const FINDS_N = {n};\nexport const FINDS_PLUS = {json.dumps(finds)};\nexport const QC_N = {qc};\nexport const QC_PLUS = {json.dumps(qcl)};\n")
    changed = []
    path = os.path.join(ROOT, "functions/_lib/counts.js")
    if not os.path.exists(path) or open(path, encoding="utf-8").read() != js:
        changed.append("functions/_lib/counts.js")
        if "--check" not in sys.argv: open(path, "w", encoding="utf-8").write(js)
    for f in FILES:
        p = os.path.join(ROOT, f)
        if not os.path.exists(p): continue
        s = open(p, encoding="utf-8").read()
        if f == "index.html":   # never inside the catalogue block
            i = s.find('id="pc-catalog">'); j = s.find("</script>", i)
            head, cat, tail = s[:i], s[i:j], s[j:]
            new = NUM.sub(finds, head) + cat + NUM.sub(finds, tail)
        else:
            new = ABOUT.sub(lambda m: m.group(1) + finds.rstrip("+") + m.group(2), NUM.sub(finds, s))
        if new != s:
            changed.append(f)
            if "--check" not in sys.argv: open(p, "w", encoding="utf-8").write(new)
    print(f"visible finds {n:,} -> {finds}, QC {qc} -> {qcl}; " + (("changed: " + ", ".join(changed)) if changed else "all up to date"))
    return 1 if ("--check" in sys.argv and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
