# -*- coding: utf-8 -*-
"""Switch the extra store angles (store-gallery.json) to their transparent cut-outs (photo_white.py --alpha group g,
owner 24 Nov 2026: dark tiles on #262626), or back.

An entry "s2/<name>" or "w/<name>" becomes "s2/<stem>-t1.webp" (products/store2/, which the page already serves for
"s2/" entries) when its data/photo_cut record is ok, not rejected in review, and uploaded (data/photo_cut_uploaded.json),
and the find still lists that entry. The same exact entries are swapped in functions/_lib/store_gallery.js (generated by
apply_store_photos.py with the same lists), so the product page and the app agree. Every swap is logged in
data/photo_cut_gallery_applied.json; --revert swaps the logged ones back. Report only without --write.

  python scripts/photo_cut_gallery.py [--ids 1,2] [--write] [--revert]
"""
import argparse, collections, glob, json, os, re, sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalog_common import ROOT, load_json, save_json  # noqa: E402

GAL = os.path.join(ROOT, "store-gallery.json")
GAL_JS = os.path.join(ROOT, "functions", "_lib", "store_gallery.js")
LOG = os.path.join(ROOT, "data", "photo_cut_gallery_applied.json")
NEW = re.compile(r"^s2/[0-9]{1,15}-[a-z]{0,2}[0-9]{1,3}-t1\.webp$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ids", default="")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--revert", action="store_true")
    a = ap.parse_args()
    only = set(a.ids.replace(" ", "").split(",")) - {""}
    gal = load_json(GAL, {})
    log = load_json(LOG, {"batches": []})
    swaps, why = [], collections.Counter()           # (id, old entry, new entry)
    if a.revert:
        done = {}
        for b in log.get("batches", []):
            for c in b.get("changes", []):
                if b.get("kind") == "apply": done[(c["id"], c["new"])] = c["old"]
                else: done.pop((c["id"], c["old"]), None)
        for (i, new), old in done.items():
            if only and i not in only: continue
            if new in (gal.get(i) or []): swaps.append((i, new, old))
            else: why["no longer listed"] += 1
    else:
        up = (load_json(os.path.join(ROOT, "data", "photo_cut_uploaded.json"), {}) or {}).get("items") or {}
        for f in sorted(glob.glob(os.path.join(ROOT, "data", "photo_cut", "*.json"))):
            for key, r in (load_json(f, {}).get("items") or {}).items():
                if r.get("group") != "g" or r.get("v") != 1: continue
                i, old = r.get("id"), r.get("entry")
                if only and i not in only: continue
                if not r.get("ok"): why["no transparent cut-out (could not make one)"] += 1; continue
                if r.get("review") == "rejected": why["rejected in review"] += 1; continue
                if key not in up: why["not uploaded yet"] += 1; continue
                new = "s2/" + up[key]["object"].split("/")[-1]
                if not NEW.match(new) or up[key]["object"] != r.get("object"): why["upload log does not match"] += 1; continue
                if new in (gal.get(i) or []): why["already shown"] += 1; continue
                if old not in (gal.get(i) or []): why["the find no longer lists that photo"] += 1; continue
                swaps.append((i, old, new))
    print(("revert" if a.revert else "switch") + ": %d gallery entries; kept: %s" % (len(swaps), dict(why)))
    if not a.write or not swaps:
        print("report only, nothing written" if not a.write else "nothing to write"); return 0
    js = open(GAL_JS, encoding="utf-8").read()
    for i, old, new in swaps:
        gal[i] = [new if e == old else e for e in gal[i]]
        q_old, q_new = json.dumps(old), json.dumps(new)
        if js.count(q_old) != 1: raise SystemExit(f"{i}: {old} is not exactly once in {GAL_JS}; nothing written")
        js = js.replace(q_old, q_new)
    save_json(GAL, gal)
    open(GAL_JS, "w", encoding="utf-8").write(js)
    log["batches"].append({"date": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "kind": "revert" if a.revert else "apply",
                           "changes": [{"id": i, "old": o, "new": n} for i, o, n in swaps]})
    save_json(LOG, log)
    print("written: store-gallery.json, functions/_lib/store_gallery.js, " + os.path.relpath(LOG, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
