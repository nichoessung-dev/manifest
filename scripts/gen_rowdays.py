#!/usr/bin/env python3
"""Writes functions/_lib/rowdays.js: for every find in the current catalogue, the day it first appeared in
functions/_lib/catalog.js and the day its row last changed, read from the git history of that file.

The server renders product pages and hubs from catalog.js, so these are the days their content really changed. The sitemaps
use them as <lastmod> (pages.js sitemapPages / sitemapProducts) instead of "today" on every URL.

Changed means a field a page shows: title, brand, category, marketplace, seller, price (cny), QC flag or count, photo,
gender, item id or colours. Views, the curated flag and the derived USD price are left out.

Run after scripts/gen_catalog.py, in a checkout with full history (actions/checkout fetch-depth: 0):
    python3 scripts/gen_rowdays.py            # uses HEAD and the working tree's catalog.js
    python3 scripts/gen_rowdays.py --ref origin/main --out /tmp/rowdays.js
A catalog.js that is not committed yet counts as BUILT (its own date) for rows that are new or changed in it.
"""
import argparse, json, os, re, subprocess, sys

CAT = "functions/_lib/catalog.js"
FIELDS = (1, 2, 3, 4, 5, 7, 8, 11, 12, 13, 14)   # see the docstring; 0 is the id

def rows_of(text):
    m = re.search(r"export const ROWS = (\[.*?\]);\s*$", text, re.S | re.M)
    if not m:
        raise SystemExit("ROWS not found")
    return json.loads(m.group(1))

def built_of(text):
    m = re.search(r'export const BUILT = "(\d{4}-\d{2}-\d{2})"', text)
    return m.group(1) if m else None

def git(*a):
    return subprocess.run(["git", *a], check=True, capture_output=True, text=True).stdout

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default="HEAD")
    ap.add_argument("--out", default="functions/_lib/rowdays.js")
    ap.add_argument("--worktree", action="store_true", default=None, help="also read the working tree's catalog.js (default when --ref is HEAD)")
    a = ap.parse_args()
    use_wt = a.worktree if a.worktree is not None else a.ref == "HEAD"
    log = git("log", "--reverse", "--format=%H %ad", "--date=short", a.ref, "--", CAT).split("\n")
    versions = [(l.split()[1], lambda h=l.split()[0]: git("show", f"{h}:{CAT}")) for l in log if l.strip()]
    if use_wt and os.path.exists(CAT):
        txt = open(CAT, encoding="utf-8").read()
        versions.append((built_of(txt) or versions[-1][0], lambda t=txt: t))
    first, changed, sig = {}, {}, {}
    for day, read in versions:
        for r in rows_of(read()):
            i = str(r[0]); s = json.dumps([r[k] if k < len(r) else None for k in FIELDS], ensure_ascii=False)
            if i not in first:
                first[i] = day; changed[i] = day
            elif sig.get(i) != s:
                changed[i] = day
            sig[i] = s
    cur = [str(r[0]) for r in rows_of(versions[-1][1]())]
    days = sorted({first[i] for i in cur} | {changed[i] for i in cur})
    di = {d: k for k, d in enumerate(days)}
    b36 = "0123456789abcdefghijklmnopqrstuvwxyz"
    if len(days) > 36:
        raise SystemExit("more than 36 distinct days: widen the encoding")
    enc = {i: b36[di[first[i]]] + b36[di[changed[i]]] for i in cur}
    out = ("// GENERATED by scripts/gen_rowdays.py from the git history of functions/_lib/catalog.js. Do not edit by hand.\n"
           "// ROWDAY[id] is two base-36 digits: the index in DAYS of the day the find first appeared, then of the day its row last changed.\n"
           f"export const DAYS = {json.dumps(days)};\n"
           f"export const ROWDAY = {json.dumps(enc, separators=(',', ':'))};\n")
    open(a.out, "w", encoding="utf-8").write(out)
    new = {}
    for i in cur: new[first[i]] = new.get(first[i], 0) + 1
    print(f"{len(cur)} finds, {len(days)} days, {len(out)//1024} KB; first seen per day: {json.dumps(new)}", file=sys.stderr)

if __name__ == "__main__":
    main()
