#!/usr/bin/env python3
"""Write the approved partner link swaps (/partner, Supabase approved_swaps()) for the server pages.

Runs in GitHub Actions (.github/workflows/swaps.yml) with the SUPABASE_SERVICE_KEY secret. Writes, only when the swaps changed:
  data/link_swaps.json          {"updated": ..., "swaps": {find id: [platform, item id]}}
  functions/_lib/link_swaps.js  export const SWAPS = {...}   (site.js puts the item id on the find: product pages, buy links)
The app (index.html) reads approved_swaps() itself, so a swap shows there at once. Ids and item ids only, no emails.
"""
import datetime, json, os, re, sys, urllib.request

SUPA = "https://uptpghuduqjqmrxwatbm.supabase.co"
OUT, JS = "data/link_swaps.json", "functions/_lib/link_swaps.js"


def main():
    key = os.environ.get("SUPABASE_SERVICE_KEY")
    if not key:
        print("no SUPABASE_SERVICE_KEY: nothing to do"); return
    req = urllib.request.Request(SUPA + "/rest/v1/rpc/approved_swaps", data=b"{}", method="POST",
                                 headers={"apikey": key, "Authorization": "Bearer " + key, "Content-Type": "application/json"})
    try:
        rows = json.load(urllib.request.urlopen(req, timeout=30))
    except Exception as e:
        print("approved_swaps() not reachable (table not set up yet?):", e); return
    swaps = {}
    for r in rows:
        pid, pl, item = str(r.get("pid") or ""), str(r.get("platform") or ""), str(r.get("item_id") or "")
        if re.fullmatch(r"[0-9A-Za-z_-]{1,40}", pid) and pl in ("weidian", "taobao", "1688") and re.fullmatch(r"[0-9]{5,20}", item):
            swaps[pid] = [pl, item]
    swaps = dict(sorted(swaps.items()))
    try:
        old = json.load(open(OUT, encoding="utf-8")).get("swaps")
    except (OSError, ValueError):
        old = None
    if old == swaps and os.path.exists(JS):
        print("no change (%d swaps)" % len(swaps)); return
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    json.dump({"updated": now, "swaps": swaps}, open(OUT, "w", encoding="utf-8"), separators=(",", ":"))
    open(JS, "w", encoding="utf-8").write(
        "// GENERATED by scripts/bake_swaps.py (Swaps workflow) from the approved partner swaps on /partner. Do not edit by hand.\n"
        "// find id -> [platform, item id]: site.js sends that find's Buy buttons to this item.\n"
        "export const SWAPS = " + json.dumps(swaps, separators=(",", ":")) + ";\n")
    print("wrote %d swaps" % len(swaps))


if __name__ == "__main__":
    sys.exit(main())
