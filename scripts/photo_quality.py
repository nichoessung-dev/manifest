#!/usr/bin/env python3
"""Photo quality score per find (owner, 10 Nov 2026: "push the bad photos down the grid").

Reads the vision labels in data/catalog_ai.json (photo_issues per find) and writes how bad each find's main photo is,
from 0 (clean) to 0.9 (unusable):
  data/photo_quality.json          {"updated": ..., "bad": {id: score}}   read by the app (index.html)
  functions/_lib/photo_quality.js  export const PQ = {id: score}           read by the server pages (site.js score)
Both rank a find lower by its score (popularity x (1 - 0.6 x score)); nothing is hidden. Only finds with a score are
listed, so a clean photo costs nothing. A find whose photo was replaced since it was labelled (data/seller_photos.json
status ok, or a cleaned photo switched on) counts as clean.

  python scripts/photo_quality.py [--dry-run]
"""
import argparse, json, os
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAG = '<script type="application/json" id="pc-catalog">'
# how much each problem hurts a shopper's first look at the card
WEIGHT = {
    "blurry_or_low_res": 0.7, "worn_by_person": 0.55, "collage_or_grid": 0.55, "text_or_watermark": 0.45,
    "multiple_items": 0.4, "hand_in_photo": 0.4, "cut_out_damage": 0.4, "busy_background": 0.35,
    "packaging_or_box": 0.35, "item_cropped": 0.35, "hanger_or_rack": 0.3, "multiple_views": 0.15,
}


def load(path, default):
    try:
        return json.load(open(os.path.join(ROOT, path), encoding="utf-8"))
    except (OSError, ValueError):
        return default


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    html = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
    i = html.index(TAG) + len(TAG)
    cat = {str(p["id"]): p for p in json.loads(html[i:html.index("</script>", i)])}
    labels = load("data/catalog_ai.json", {}).get("items", {})
    seller = load("data/seller_photos.json", {})
    seller = seller.get("items", seller) if isinstance(seller, dict) else {}
    bad = {}
    for pid, lab in labels.items():
        p = cat.get(pid)
        if not p:
            continue
        if (seller.get(pid) or {}).get("status") == "ok" or "/img/p2/" in (p.get("img") or "") or "/products/pc2/" in (p.get("img") or ""):
            continue   # a new photo since the label
        keep = 1.0
        for issue in set(lab.get("photo_issues") or []):
            keep *= 1 - WEIGHT.get(issue, 0.2)
        score = round(min(0.9, 1 - keep), 2)
        if score >= 0.1:
            bad[pid] = score
    buckets = {}
    for s in bad.values():
        k = "0.6+" if s >= 0.6 else "0.3-0.6" if s >= 0.3 else "0.1-0.3"
        buckets[k] = buckets.get(k, 0) + 1
    print("finds %d, labelled %d, with a photo score %d %s" % (len(cat), len(labels), len(bad), buckets))
    if a.dry_run:
        return
    out = {"updated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "bad": dict(sorted(bad.items()))}
    json.dump(out, open(os.path.join(ROOT, "data", "photo_quality.json"), "w", encoding="utf-8"), separators=(",", ":"))
    js = ("// GENERATED by scripts/photo_quality.py from data/catalog_ai.json: how bad each find's main photo is (0 to 0.9).\n"
          "// site.js score() ranks a find lower by it. Do not edit by hand.\n"
          "export const PQ = " + json.dumps(dict(sorted(bad.items())), separators=(",", ":")) + ";\n")
    open(os.path.join(ROOT, "functions", "_lib", "photo_quality.js"), "w", encoding="utf-8").write(js)


if __name__ == "__main__":
    main()
